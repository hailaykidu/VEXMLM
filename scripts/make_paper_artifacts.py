#!/usr/bin/env python3
"""Generate every number, table body and figure in the paper from stored result files.

    python scripts/make_paper_artifacts.py --results results --out paper/generated
    python scripts/make_paper_artifacts.py --check      # fail if generated files would change

Deterministic: reads only result files in the repository and performs no training or
evaluation. Every number comes from stored results of runs made before the correction (GitHub, the
Hugging Face model card, or earlier local run records); nothing is computed anew. Numbers are
reported exactly as the repository's public result files (and the Hugging Face model cards) state them (stated once in the paper):
  * VEXMLM downstream scores are the strings in results/downstream_task_metrics.csv
    (NER/SA accuracy and F1 as fractions, 4 decimals; QA EM/F1 in %, 2 decimals), and
    ablation scores and deltas the strings in results/table5_ablation.csv (%, 2 decimals);
    both are re-checked against the per-seed result files;
  * the single-seed XLM-R baseline uses the same unit and precision as the matching VEXMLM value;
  * differences are computed from unrounded means, as in the repository's tables;
  * tokenizer metrics have 4 decimals, as in results/spmerge_tokenizer_metrics.json.
"""
